using PaydayGlow.Core;

int count = 0;
void Check(bool value, string name) { if (!value) throw new Exception("FAILED: " + name); Console.WriteLine("PASS " + name); count++; }
bool Near(double a, double b) => Math.Abs(a - b) < 0.000001;
var zone = TimeZoneInfo.CreateCustomTimeZone("Test +08", TimeSpan.FromHours(8), "Test", "Test");
var settings = new WageSettings { MonthlySalary = 21500 };
DateTimeOffset Date(int day, int hour, int minute = 0, int second = 0) => new(2026, 10, day, hour, minute, second, TimeSpan.FromHours(8));
WageSnapshot Snap(int day, int hour, int minute = 0, int second = 0, bool awake = true) => WageEngine.Snapshot(Date(day, hour, minute, second), settings, awake, zone);
Check(settings.Validate() is null, "default settings valid");
Check(Near(Snap(22, 10).AverageDays, 21.5), "fixed monthly average 21.5");
Check(Near(Snap(22, 10).DayPay, 1000), "daily income uses 21.5");
Check(Near(Snap(22, 10).SecondPay, 1000.0 / 28800), "per second rate deducts lunch");
Check(Snap(22, 8).Phase == WorkPhase.Before && Snap(22, 8).Earned == 0, "before work earns zero");
Check(Snap(22, 9).Phase == WorkPhase.Working && Snap(22, 9).Earned == 0, "shift starts exactly");
Check(Near(Snap(22, 10).Earned, 125), "one paid hour");
Check(Snap(22, 12).Phase == WorkPhase.OnBreak, "lunch starts exactly");
Check(Near(Snap(22, 12, 30).Earned, 375), "lunch pauses earnings");
Check(Snap(22, 13).Phase == WorkPhase.Working && Near(Snap(22, 13).Earned, 375), "lunch ends exactly");
Check(Snap(22, 17, 59, 59).Remaining == 1, "one second before finish");
Check(Snap(22, 18).Phase == WorkPhase.Overtime && Near(Snap(22, 18).Earned, 1000), "exact end caps income");
Check(Snap(22, 20).Overtime == 7200 && Snap(22, 20).Phase == WorkPhase.Overtime, "lit screen overtime");
Check(Near(Snap(22, 20).Earned, 1000), "overtime does not increase income");
Check(Snap(22, 20, awake: false).Phase == WorkPhase.Finished, "screen off is not overtime");
Check(Snap(25, 20).Phase == WorkPhase.Rest && Snap(25, 20).Earned == 0, "Sunday rest");
Check(Near(Snap(22, 10, awake: false).Earned, 125), "screen sleep does not deduct scheduled income");
settings = settings with { HasBreak = false };
Check(Near(Snap(22, 10).SecondPay, 1000.0 / 32400), "no lunch counts nine hours");
settings = settings with { StartMinute = 1320, EndMinute = 360 };
Check(settings.Validate() is null, "overnight valid");
Check(Snap(23, 2).Phase == WorkPhase.Working && Near(Snap(23, 2).Earned, 500), "overnight yesterday shift");
Check(Snap(23, 6).Phase == WorkPhase.Overtime && Near(Snap(23, 6).Earned, 1000), "overnight morning end");
Check(Snap(24, 2).Phase == WorkPhase.Working, "Friday overnight Saturday");
Check(Snap(25, 2).Phase == WorkPhase.Rest, "Saturday overnight rest");
settings = settings with { HasBreak = true, BreakStartMinute = 120, BreakEndMinute = 180 };
Check(settings.Validate() is null && Snap(23, 2, 30).Phase == WorkPhase.OnBreak, "overnight lunch");
Check((settings with { BreakEndMinute = 1260 }).Validate() is not null, "out of shift lunch rejected");
Check((new WageSettings { MonthlySalary = 0 }).Validate() is not null, "zero pay rejected");
Check((new WageSettings { MonthlySalary = double.NaN }).Validate() is not null, "nan pay rejected");
Check((new WageSettings { MonthlySalary = double.PositiveInfinity }).Validate() is not null, "infinite pay rejected");
Check((new WageSettings { Weekdays = [] }).Validate() is not null, "empty workweek rejected");
Check((new WageSettings { Weekdays = null! }).Validate() is not null, "null workweek rejected");
Check((new WageSettings { Weekdays = [9] }).Validate() is not null, "invalid weekday rejected");
Check((new WageSettings { EndMinute = 540 }).Validate() is not null, "zero shift rejected");
Check((new WageSettings { BreakEndMinute = 720 }).Validate() is not null, "zero lunch rejected");
Check((new WageSettings { StartMinute = -1 }).Validate() is not null, "invalid start rejected");
Check((new WageSettings { EndMinute = 1440 }).Validate() is not null, "invalid end rejected");
Check(WageEngine.Duration(3599.1) == "01:00:00" && WageEngine.Duration(-1) == "00:00:00", "countdown rounding");
settings = new WageSettings();
Check(!WageEngine.ShouldRemind(Snap(22, 17, 59, 59), true, true, null), "no early reminder");
Check(!WageEngine.ShouldRemind(Snap(22, 18), false, true, null), "unconfigured no reminder");
Check(!WageEngine.ShouldRemind(Snap(22, 18), true, false, null), "screen sleep defers reminder");
Check(WageEngine.ShouldRemind(Snap(22, 18), true, true, null), "finish reminder");
Check(!WageEngine.ShouldRemind(Snap(22, 20), true, true, Snap(22, 18).ShiftId), "no duplicate reminder");
Check(WageEngine.ShouldRemind(Snap(23, 18), true, true, Snap(22, 18).ShiftId), "next day reminder");
Check(!WageEngine.ShouldRemind(Snap(25, 18), true, true, null), "rest day no reminder");
var first = Snap(22, 15); var later = Snap(22, 15, 0, 5);
Check(first.Remaining - later.Remaining == 5, "five second countdown");
Check(Near(later.Earned - first.Earned, first.SecondPay * 5), "five second earnings");
var temp = Path.Combine(Path.GetTempPath(), "PaydayGlow.Tests." + Guid.NewGuid());
try
{
    var store = new SettingsStore(temp);
    Check(!store.Load().Configured, "first run does not preload a personal salary");
    var saved = new SavedState { Configured = true, Settings = settings, LastShiftId = "sample-shift" };
    store.Save(saved);
    var loaded = new SettingsStore(temp).Load();
    Check(loaded.Configured && loaded.Settings.MonthlySalary == settings.MonthlySalary, "settings survive restart");
    Check(loaded.LastShiftId == "sample-shift", "reminder marker survives restart");
    Check(loaded.Settings.Weekdays.SequenceEqual(settings.Weekdays), "workdays persist");
    File.WriteAllText(store.FilePath, "broken json");
    Check(!store.Load().Configured && store.LoadWarning is not null, "corrupt settings fallback");
    Check(File.ReadAllText(store.FilePath) == "broken json", "corrupt settings not overwritten automatically");
    File.WriteAllText(store.FilePath, "{\"Configured\":true,\"Settings\":null}");
    Check(!store.Load().Configured, "null settings fallback");
    store.Save(saved);
    Check(Directory.GetFiles(temp, "*.tmp").Length == 0, "atomic save cleans temporary files");
}
finally { if (Directory.Exists(temp)) Directory.Delete(temp, true); }
Console.WriteLine($"{count} checks passed.");
